#!/usr/bin/env python3
"""Build src/collect/spec.toml from `rgmond dump` output: the exact metadata and
value format C gmond used for each of its own metrics, one entry per name.
Per-device, interface, mount and process families are then written as "{}"
patterns in spec.toml so the file is not tied to one host."""
import re, sys, json

# usage: extract_spec.py DUMP SRC_IP OUT [EXCLUDE_REGEX]
# EXCLUDE_REGEX skips metrics that gmetric scripts on the same host send from
# gmond's address, which are not gmond's own.
dump, src_ip, out = sys.argv[1], sys.argv[2], sys.argv[3]
GMETRIC = re.compile(sys.argv[4] if len(sys.argv) > 4 else r'(?!)')

def pstr(s):  # Rust Debug string -> python str
    return json.loads(s)

meta, vals = {}, {}
for line in open(dump):
    ts, ip, msg = line.rstrip('\n').split('\t', 2)
    if ip != src_ip:
        continue
    m = re.match(r'MetadataFull \{ id: MetricId \{ host: ("(?:[^"\\]|\\.)*"), name: ("(?:[^"\\]|\\.)*"), spoof: (\w+) \}, meta: Metadata \{ type_: ("(?:[^"\\]|\\.)*"), name: ("(?:[^"\\]|\\.)*"), units: ("(?:[^"\\]|\\.)*"), slope: (\d+), tmax: (\d+), dmax: (\d+), extra: \[(.*)\] \} \}$', msg)
    if m:
        name = pstr(m[2])
        extra = re.findall(r'\(("(?:[^"\\]|\\.)*"), ("(?:[^"\\]|\\.)*")\)', m[10])
        meta[name] = dict(type=pstr(m[4]), units=pstr(m[6]), slope=int(m[7]), tmax=int(m[8]), dmax=int(m[9]),
                          extra=[[pstr(a), pstr(b)] for a, b in extra])
        continue
    m = re.match(r'Value \{ id: MetricId \{ host: ("(?:[^"\\]|\\.)*"), name: ("(?:[^"\\]|\\.)*"), spoof: (\w+) \}, fmt: ("(?:[^"\\]|\\.)*"), value: (\w+)\(', msg)
    if m:
        vals[pstr(m[2])] = dict(fmt=pstr(m[4]), wire=m[5])

names = sorted(n for n in set(meta) | set(vals) if not GMETRIC.match(n))
with open(out, 'w') as f:
    f.write('# Generated by tools/extract_spec.py from the phase 0 capture: the metadata\n'
            '# and value encoding C gmond 3.7.2 used for each built-in metric.\n\n')
    for n in names:
        md, v = meta.get(n), vals.get(n)
        if not md or not v:
            print(f'warning: {n}: metadata={bool(md)} value={bool(v)}', file=sys.stderr)
            continue
        f.write(f'[[metric]]\nname = {json.dumps(n)}\ntype = {json.dumps(md["type"])}\n'
                f'units = {json.dumps(md["units"])}\nslope = {md["slope"]}\ntmax = {md["tmax"]}\n'
                f'dmax = {md["dmax"]}\nfmt = {json.dumps(v["fmt"])}\nwire = {json.dumps(v["wire"])}\n'
                f'extra = {json.dumps(md["extra"])}\n\n')
print(f'{len(names)} metrics', file=sys.stderr)
