#!/usr/bin/env python3
"""Translate gmond's libconfuse config (gmond.conf + included *.pyconf) into
rgmond's [collectors] TOML: collection groups and per-module params.

usage: convert_conf.py /etc/ganglia/gmond.conf > collectors.toml
"""
import glob, json, os, re, sys

def tokens(text):
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    out = []
    for line in text.splitlines():
        i = 0
        while i < len(line):
            c = line[i]
            if c.isspace():
                i += 1
            elif c == '#' or line.startswith('//', i):
                break
            elif c in '{}=(),':
                out.append(c); i += 1
            elif c in '"\'':
                j = line.index(c, i + 1)
                out.append(('str', line[i + 1:j])); i = j + 1
            else:
                m = re.match(r'[^\s{}=(),"\']+', line[i:])
                out.append(m.group(0)); i += len(m.group(0))
    return out

def parse(toks, i=0, end=None):
    """-> list of (key, title_or_None, value_or_block)"""
    items = []
    while i < len(toks):
        t = toks[i]
        if t == '}':
            return items, i + 1
        key = t if isinstance(t, str) else t[1]
        i += 1
        if key == 'include' and toks[i] == '(':
            items.append(('include', None, toks[i + 1][1])); i += 3
            continue
        title = None
        if i < len(toks) and toks[i] not in ('{', '='):
            title = toks[i][1] if isinstance(toks[i], tuple) else toks[i]; i += 1
        if toks[i] == '{':
            block, i = parse(toks, i + 1)
            items.append((key, title, block))
        elif toks[i] == '=':
            v = toks[i + 1]; i += 2
            items.append((key, title, v[1] if isinstance(v, tuple) else v))
    return items, i

def load(path):
    items, _ = parse(tokens(open(path).read()))
    out = []
    for k, t, v in items:
        if k == 'include':
            for p in sorted(glob.glob(v if os.path.isabs(v) else os.path.join(os.path.dirname(path), v))):
                out += load(p)
        else:
            out.append((k, t, v))
    return out

def get(block, key, default=None):
    for k, _, v in block:
        if k == key:
            return v
    return default

def scalar(v):
    if v in ('yes', 'true'): return 'true'
    if v in ('no', 'false'): return 'false'
    try:
        float(v); return v
    except (TypeError, ValueError):
        return json.dumps(v)

items = load(sys.argv[1])
print('# Generated by tools/convert_conf.py from', sys.argv[1])
for k, _, block in items:
    if k != 'modules':
        continue
    for mk, _, mod in block:
        if mk != 'module' or get(mod, 'language') != 'python':
            continue
        print(f'\n[collectors.params.{get(mod, "name")}]')
        for pk, ptitle, pblock in mod:
            if pk == 'param':
                print(f'{json.dumps(ptitle)} = {json.dumps(get(pblock, "value"))}')
for k, _, block in items:
    if k != 'collection_group':
        continue
    print('\n[[collectors.group]]')
    if get(block, 'collect_once') in ('yes', 'true'):
        print('collect_once = true')
    if get(block, 'collect_every') is not None:
        print(f'collect_every = {get(block, "collect_every")}')
    print(f'time_threshold = {get(block, "time_threshold", "3600")}')
    for mk, _, m in block:
        if mk != 'metric':
            continue
        sel = [f'name = {json.dumps(get(m, "name"))}'] if get(m, 'name') else [f'name_match = {json.dumps(get(m, "name_match"))}']
        if get(m, 'value_threshold') is not None:
            sel.append(f'value_threshold = {float(get(m, "value_threshold"))}')
        print('[[collectors.group.metric]]\n' + '\n'.join(sel))
